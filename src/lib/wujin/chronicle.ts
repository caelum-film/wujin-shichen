export function hourIds(ids: Set<string>) {
  return stalls.filter((stall) => ids.has(stall.id));
}

export function streetTalk(count: number) {
  if (count <= 0) return "城里有人把名字投进了潮里。潮还没决定要不要还。";
  if (count < 4) return "阿迟的名字已经在铺子之间走动。它还没决定今晚要落在谁的袖口。";
  if (count < 8) return "有几间铺认了你。名字走到半路，开始有了影子和温度。";
  if (count < 12) return "长夜快写完了。剩下的时辰不催你，只把灯留着。";
  return "十二时都走过了。雾会散。城门为肯把自己带上岸的人开了一寸。";
}
