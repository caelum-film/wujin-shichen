const ferrymanClosings = [
  "舱里只有这一句。江听完，把船推开半尺，像在说：还可以再来。",
  "句子开始彼此认得。老周不把它编成故事，他怕编了以后，你的原话就失踪。",
  "夜已经有了形状。形状不是圆的，是你走过的那些铺连起来的折线。",
  "他把桨放下。放下的意思是：这些话自己会浮，不必再划。",
];

export function ferrymanLetter(slips: Slip[]) {
  if (slips.length === 0) {
    return {
      title: "空舱",
      paragraphs: [
        "老周把桨横在膝上。舱里没有你的句子。",
        "船还在。你还没有把任何一张夜笺交给这夜里。他可以等。等的时候，第三类潮会在桥洞里自己练习，不劳你答应。",
      ],
    };
  }
  const picked = slips.slice(0, 4);
  const quotes = picked.map((slip) => {
    const line = slip.body.split("\n").find((item) => item.trim()) ?? "";
    return `「${slip.title}」里，他拣到这一句：${line}`;
  });
  const closing =
    ferrymanClosings[Math.min(slips.length, ferrymanClosings.length) - 1] ??
    ferrymanClosings[0];
  return {
    title: slips.length >= 8 ? "可以靠岸的信" : "舱里的信",
    paragraphs: [
      `老周把你的 ${slips.length} 张夜笺摊开，不按时间，按它们自己愿意靠近的顺序。`,
      ...quotes,
      closing ?? "",
    ],
  };
}

