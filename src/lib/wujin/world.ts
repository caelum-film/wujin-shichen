export function returnLost(ids: string[]) {
  const picked = ids
    .map((id) => lostLines.find((item) => item.id === id))
    .filter((item): item is (typeof lostLines)[number] => Boolean(item));
  const extra = ids.includes("name")
    ? "阿迟在码头看见自己的小名回来，没有再投。他只是把袖口又弄湿了一点，像问好。"
    : "城里轻了一寸。轻，不是失去，是各物回到了肯负责的人手里。";
  return {
    title: "闰时 · 拾遗",
    paragraphs: [
      "闰时没有钟点。它夹在你已经走过的铺与还没走过的铺之间，专门收留被谁放下又还没人认的东西。",
      ...picked.map((item) => `${item.label}：${item.back}`),
      extra,
    ],
  };
}
